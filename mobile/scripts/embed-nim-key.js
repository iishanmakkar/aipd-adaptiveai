#!/usr/bin/env node
/*
 * Writes src/services/embeddedKey.ts with the real NIM key so the next assembleRelease bakes
 * it into the JS bundle. The target file is git-ignored — the key never enters the repo.
 *
 * Key source, in order: $NIM_KEY, then backend/.env (NIM_API_KEY=...), then agents/.env,
 * intent-engine/.env at the repo root. Prints only the key's prefix, never the full value.
 *
 * Usage:  node scripts/embed-nim-key.js            # embed if a key is found
 *         node scripts/embed-nim-key.js --clear    # restore the empty default
 */
const fs = require('fs');
const path = require('path');

const MOBILE = path.resolve(__dirname, '..');
const TARGET = path.join(MOBILE, 'src', 'services', 'embeddedKey.ts');
const REPO = path.resolve(MOBILE, '..');

function findKey() {
  if (process.env.NIM_KEY) return process.env.NIM_KEY.trim();
  for (const rel of ['backend/.env', 'agents/.env', 'intent-engine/.env']) {
    const p = path.join(REPO, rel);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^NIM_API_KEY=(.+)$/m);
    if (m) {
      return m[1].trim().replace(/^["']|["']$/g, '');
    }
  }
  return '';
}

const HEADER = `// BUILD-LOCAL, GIT-IGNORED — contains the real NIM key when present. Never commit this file.
// Regenerated by \`node scripts/embed-nim-key.js\` before assembleRelease; the committed
// default is an empty string, which means "no key embedded" and the app falls back to the
// Keystore key the user enters in Settings.
//
// Security note, stated plainly: a key inside an APK is extractable by anyone who has the
// APK. Embedding is only safe with a key you are willing to rotate on exposure.
`;

if (process.argv.includes('--clear')) {
  fs.writeFileSync(TARGET, `${HEADER}export const EMBEDDED_NIM_KEY = '';\n`);
  console.log('embeddedKey.ts: cleared (empty default)');
  process.exit(0);
}

const key = findKey();
if (!key.startsWith('nvapi-')) {
  console.log('no nvapi- key found (NIM_KEY env or backend/.env) — writing empty default; the app will ask for a key in Settings');
  fs.writeFileSync(TARGET, `${HEADER}export const EMBEDDED_NIM_KEY = '';\n`);
  process.exit(0);
}

// Escape for a TS string literal without ever printing the value.
const escaped = JSON.stringify(key);
fs.writeFileSync(TARGET, `${HEADER}export const EMBEDDED_NIM_KEY = ${escaped};\n`);
console.log(`embeddedKey.ts: wrote key ${key.slice(0, 9)}…${key.slice(-4)} (${key.length} chars) — file is git-ignored`);
